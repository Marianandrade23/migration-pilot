"""Step 3: write the conversion code and its tests from the approved mapping.

The generated module is what the migration actually runs, so a reviewer can read exactly how
every field is converted. The generated tests check the output contract of each field
(ZIP is 5 digits, dates are ISO, states are 2 capital letters, and so on) on real sample rows.
"""

from __future__ import annotations

import importlib.util
import os
import pprint
import re
import subprocess
import sys
from pathlib import Path
from types import ModuleType

from .profiler import ColumnProfile
from .transforms import infer_boolean_map

GENERATED_DIR = Path(__file__).resolve().parent.parent / "generated"

CONTRACTS = {
    "text": "isinstance(v, str) and v.strip() == v and v != ''",
    "state": "isinstance(v, str) and len(v) == 2 and v.isupper()",
    "zip": "isinstance(v, str) and re.fullmatch(r'\\d{5}', v) is not None",
    "phone": "isinstance(v, str) and re.fullmatch(r'\\(\\d{3}\\) \\d{3}-\\d{4}', v) is not None",
    "email": "isinstance(v, str) and '@' in v and v == v.lower()",
    "currency": "isinstance(v, float) and v >= 0",
    "date": "isinstance(v, str) and re.fullmatch(r'\\d{4}-\\d{2}-\\d{2}', v) is not None",
    "boolean": "isinstance(v, bool)",
}


def _literal(value: object) -> str:
    return pprint.pformat(value, sort_dicts=False, width=100)


def slugify(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")[:40] or "migration"


def boolean_value_maps(
    mapping: dict[str, str | None], profiles: list[ColumnProfile], target: list[dict],
) -> tuple[dict[str, dict[str, bool]], list[str]]:
    """Work out true/false meaning for code columns mapped to boolean fields."""
    types = {str(t["name"]): str(t["type"]) for t in target}
    by_name = {p.name: p for p in profiles}
    maps, problems = {}, []
    for src, tgt in mapping.items():
        if tgt and types.get(tgt) == "boolean":
            codes = {c.strip() for c in by_name[src].detail.replace("values:", "").split(",") if c.strip()}
            value_map, unknown = infer_boolean_map(codes)
            maps[src] = value_map
            if unknown:
                problems.append(f"{src}: no true/false meaning for {', '.join(unknown)}")
    return maps, problems


def render_module(
    migration: str, mapping: dict[str, str | None], target: list[dict],
    value_maps: dict[str, dict[str, bool]],
) -> str:
    types = {str(t["name"]): str(t["type"]) for t in target}
    lines = [
        f'"""Conversion code for: {migration}.',
        "",
        "Generated by MigrationPilot from the approved mapping. Regenerate instead of editing by hand.",
        '"""',
        "",
        "from migration_pilot import transforms as t",
        "",
        f"MAPPING = {_literal(mapping)}",
        f"BOOLEAN_MAPS = {_literal(value_maps)}",
        "",
        "",
        "def transform_row(row: dict) -> tuple[dict, list[str]]:",
        '    """Convert one old record. Returns (new record, problems found)."""',
        "    out, errors = {}, []",
    ]
    for src, tgt in mapping.items():
        if not tgt:
            continue
        kind = types[tgt]
        call = (f"t.to_boolean(row.get({src!r}), BOOLEAN_MAPS[{src!r}])" if kind == "boolean"
                else f"t.{'to_' + kind}(row.get({src!r}))")
        lines += [
            f"    value, err = {call}",
            f"    out[{tgt!r}] = value",
            "    if err:",
            f"        errors.append({src + ' -> ' + tgt + ': '!r} + err)",
        ]
    lines += ["    return out, errors", ""]
    return "\n".join(lines)


def render_tests(mapping: dict[str, str | None], target: list[dict], samples: list[dict]) -> str:
    types = {str(t["name"]): str(t["type"]) for t in target}
    checks = {tgt: CONTRACTS[types[tgt]] for tgt in mapping.values() if tgt}
    return "\n".join([
        '"""Generated tests: every converted field must meet the new system\'s format."""',
        "",
        "import re",
        "",
        "import pytest",
        "",
        "from transform import transform_row",
        "",
        f"SAMPLES = {_literal(samples)}",
        "",
        "CONTRACTS = {",
        *[f"    {tgt!r}: lambda v: {expr}," for tgt, expr in checks.items()],
        "}",
        "",
        "",
        '@pytest.mark.parametrize("row", SAMPLES)',
        "def test_fields_meet_format(row):",
        "    out, errors = transform_row(row)",
        "    for field, check in CONTRACTS.items():",
        "        value = out.get(field)",
        "        if value is not None:",
        "            assert check(value), f'{field} = {value!r}'",
        "    for problem in errors:",
        "        assert ' -> ' in problem",
        "",
    ])


def generate(
    migration: str, mapping: dict[str, str | None], target: list[dict],
    value_maps: dict[str, dict[str, bool]], rows: list[dict], out_root: Path = GENERATED_DIR,
) -> Path:
    """Write transform.py and test_transform.py; return the folder."""
    folder = Path(out_root) / slugify(migration)
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "transform.py").write_text(render_module(migration, mapping, target, value_maps))
    (folder / "test_transform.py").write_text(render_tests(mapping, target, rows[:25]))
    return folder


def load_transform(folder: Path) -> ModuleType:
    spec = importlib.util.spec_from_file_location(f"generated_{folder.name}", Path(folder) / "transform.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def run_generated_tests(folder: Path) -> tuple[bool, str]:
    root = Path(__file__).resolve().parent.parent
    proc = subprocess.run(
        [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", str(folder)],
        capture_output=True, text=True, cwd=folder,
        env={**os.environ, "PYTHONPATH": f"{folder}{os.pathsep}{root}"},
    )
    last = proc.stdout.strip().splitlines()[-1] if proc.stdout.strip() else proc.stderr[-300:]
    return proc.returncode == 0, last
